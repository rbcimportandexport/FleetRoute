export function getCurrentLanguage() {
  if (typeof window !== 'undefined') {
    return localStorage.getItem('fleetroute_lang') || 'hi'; // Default to Hindi for high Indian logistics friendliness
  }
  return 'hi';
}

export function setCurrentLanguage(langCode) {
  if (typeof window !== 'undefined') {
    localStorage.setItem('fleetroute_lang', langCode);
    window.dispatchEvent(new Event('fleetroute_lang_changed'));
  }
}

export function t(key, lang, params = {}) {
  const current = lang || getCurrentLanguage();
  const dict = translations[current] || translations.en;
  let text = dict[key] || translations.en[key] || key;

  // Replace {param} placeholders
  Object.keys(params).forEach(p => {
    text = text.replace(new RegExp(`\\{${p}\\}`, 'g'), params[p]);
  });

  return text;
}
